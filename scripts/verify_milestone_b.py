"""Offline independent DOM audit of an already downloaded SEC dataset."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from hashlib import sha256
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from bs4 import BeautifulSoup
from app.financial_ingestion.html_parser import normalized_filing_text
from app.financial_ingestion.pipeline import FinancialCorpusPipeline
from app.financial_ingestion.registry import FinancialRegistry
from app.financial_ingestion.schemas import FilingMetadata, StructuredFiling


def audit(root: Path, dataset: str) -> dict:
    registry = FinancialRegistry(root / "registry.sqlite3")
    pipeline = FinancialCorpusPipeline(root=root, registry=registry)
    rows = registry.list_filings(dataset)
    assert rows, "Dataset must contain a downloaded filing"
    result = {"timestamp_utc": datetime.now(timezone.utc).isoformat(),
              "dataset_id": dataset, "filings": []}
    for row in rows:
        metadata = FilingMetadata.model_validate_json(row["metadata_json"])
        raw = Path(row["raw_path"]).read_bytes()
        filing = StructuredFiling.model_validate_json(Path(row["structured_path"]).read_text("utf-8"))
        soup = BeautifulSoup(raw, "html.parser")
        source_tables = soup.find_all("table")
        assert len(source_tables) == len(filing.tables)
        checked = 0
        mismatches = []
        examples = []
        value_matrix = []
        for source, table in zip(source_tables, filing.tables):
            source_rows = [row for row in source.find_all("tr") if row.find_parent("table") is source]
            source_grid = {}
            for source_row_index, source_row in enumerate(source_rows):
                column = 0
                for original in source_row.find_all(["td", "th"], recursive=False):
                    while (source_row_index, column) in source_grid:
                        column += 1
                    value = " ".join(original.get_text(" ", strip=True).replace("\xa0", " ").split())
                    rowspan, colspan = int(original.get("rowspan", 1)), int(original.get("colspan", 1))
                    for dr in range(rowspan):
                        for dc in range(colspan):
                            source_grid[source_row_index + dr, column + dc] = value
                    column += colspan
            for cell in table.cells:
                # Source row and cell order are read independently with BeautifulSoup.
                candidates = source_rows[cell.row].find_all(["td", "th"], recursive=False)
                prior = [c for c in table.cells if c.row == cell.row and c.column < cell.column]
                original = candidates[len(prior)]
                expected = " ".join(original.get_text(" ", strip=True).replace("\xa0", " ").split())
                checked += 1
                if expected != cell.text:
                    mismatches.append({"table": table.table_id, "row": cell.row,
                                       "column": cell.column, "source": expected, "extracted": cell.text})
                assert int(original.get("rowspan", 1)) == cell.rowspan
                assert int(original.get("colspan", 1)) == cell.colspan
            text = source.get_text(" ", strip=True).upper()
            keys = [name for name in ("TOTAL ASSETS", "TOTAL NET SALES",
                    "CASH GENERATED BY OPERATING ACTIVITIES", "WEIGHTED-AVERAGE BASIC SHARES")
                    if name in text]
            if keys:
                examples.append({"labels": keys, "table_id": table.table_id,
                                 "columns": table.columns, "units": table.units,
                                 "reporting_periods": table.reporting_periods,
                                 "extraction_status": table.extraction_status,
                                 "rows": table.rows[:8],
                                 "source_location": table.source_location.model_dump(exclude_none=True)})
                for label in ("Total assets", "Total net sales", "Cash generated by operating activities",
                              "Weighted-average basic shares outstanding"):
                    matches = [cell for cell in table.cells if cell.text == label]
                    for label_cell in matches[:1]:
                        row_cells = [cell for cell in table.cells if cell.row == label_cell.row]
                        for cell in row_cells:
                            if not any(character.isdigit() for character in cell.text):
                                continue
                            # Read header context directly from original source cells by source row.
                            # Dates/durations are not inferred from the filing's fiscal period.
                            expected_header = table.columns[cell.column]
                            components = expected_header.split(" / ") if expected_header else []
                            above = [source_grid.get((index, cell.column), "") for index in range(cell.row)]
                            context_supported = bool(components) and all(part in above for part in components)
                            source_value = source_grid[cell.row, cell.column]
                            value_matrix.append({"table_id": table.table_id, "statement": table.statement_title,
                                "row_label": label, "source_row": cell.row, "source_column": cell.column,
                                "period": expected_header, "unit": table.unit_context,
                                "source_value": source_value, "extracted_value": cell.text,
                                "header_supported_by_source": context_supported,
                                "result": "PASS" if context_supported and table.unit_context
                                and source_value == cell.text else "PARTIAL"})
        raw_hash = sha256(raw).hexdigest()
        normalized_hash = sha256(normalized_filing_text(filing).encode()).hexdigest()
        assert raw_hash == metadata.raw_content_hash
        assert normalized_hash == metadata.normalized_content_hash
        chunks = [json.loads(line) for line in Path(row["chunks_path"]).read_text("utf-8").splitlines()]
        selected = []
        for kind in ("text", "table"):
            candidates = [chunk for chunk in chunks if chunk["kind"] == kind]
            selected.extend(candidates[::max(1, len(candidates) // 6)][:6])
        provenance = [pipeline.evidence(chunk["chunk_id"]) for chunk in selected]
        assert all(item["status"] == "VERIFIED" for item in provenance)
        before_ids = sorted(chunk["chunk_id"] for chunk in chunks)
        before_manifest = pipeline.create_manifest(dataset)
        before_raw = len(list((root / "raw").rglob("*.htm")))
        reused = pipeline.ingest_one(dataset, metadata.model_copy(deep=True))
        after_manifest = pipeline.create_manifest(dataset)
        after_ids = sorted(item[0] for item in registry.connect().execute(
            "SELECT chunk_id FROM chunks WHERE filing_id=?", (metadata.filing_id,)))
        assert reused["idempotent_reuse"] is True
        assert before_ids == after_ids
        assert before_manifest.manifest_hash == after_manifest.manifest_hash
        assert before_raw == len(list((root / "raw").rglob("*.htm")))
        result["filings"].append({"metadata": metadata.model_dump(mode="json"),
            "raw_hash_verified": raw_hash, "normalized_hash_verified": normalized_hash,
            "tables": len(filing.tables), "cells_checked": checked, "cell_mismatches": mismatches,
            "value_matrix": value_matrix,
            "statement_examples": examples, "chunks": len(chunks),
            "provenance": provenance, "idempotent_reuse": True,
            "stable_chunk_ids": before_ids == after_ids, "raw_snapshots": before_raw,
            "manifest": after_manifest.model_dump(mode="json")})
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--dataset-id", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = audit(args.root, args.dataset_id)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps([{key: row[key] for key in ("tables", "cells_checked", "cell_mismatches",
          "chunks", "idempotent_reuse", "stable_chunk_ids")} for row in result["filings"]]))
    sys.exit(1 if any(row["cell_mismatches"] for row in result["filings"]) else 0)
